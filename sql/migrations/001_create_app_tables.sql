-- Core configuration and audit objects.
-- Run with a connection whose current database and schema are the application target.

CREATE TABLE IF NOT EXISTS BUDGETS (
    BUDGET_NAME VARCHAR NOT NULL,
    SCOPE_TYPE VARCHAR NOT NULL,
    SCOPE_VALUE VARCHAR NOT NULL,
    MONTHLY_LIMIT_CREDITS NUMBER(20, 6) NOT NULL,
    WARNING_THRESHOLD NUMBER(5, 4) NOT NULL DEFAULT 0.70,
    CRITICAL_THRESHOLD NUMBER(5, 4) NOT NULL DEFAULT 0.90,
    ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    UPDATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CONSTRAINT PK_BUDGETS PRIMARY KEY (BUDGET_NAME)
);

CREATE TABLE IF NOT EXISTS OWNERSHIP_MAPPINGS (
    SERVICE_TYPE VARCHAR NOT NULL,
    WORKLOAD_NAME VARCHAR NOT NULL,
    TEAM VARCHAR NOT NULL DEFAULT 'Unassigned',
    COST_CENTER VARCHAR NOT NULL DEFAULT 'Unassigned',
    ENVIRONMENT VARCHAR NOT NULL DEFAULT 'Production',
    ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    UPDATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CONSTRAINT PK_OWNERSHIP_MAPPINGS PRIMARY KEY (SERVICE_TYPE, WORKLOAD_NAME)
);

CREATE TABLE IF NOT EXISTS ALERT_HISTORY (
    ALERT_ID VARCHAR NOT NULL DEFAULT UUID_STRING(),
    BUDGET_NAME VARCHAR,
    THRESHOLD NUMBER(5, 4),
    OBSERVED_CREDITS NUMBER(20, 6),
    STATUS VARCHAR NOT NULL,
    TRIGGERED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    RESOLVED_AT TIMESTAMP_LTZ,
    RESOLUTION_NOTES VARCHAR,
    CONSTRAINT PK_ALERT_HISTORY PRIMARY KEY (ALERT_ID)
);

CREATE TABLE IF NOT EXISTS SCHEMA_MIGRATIONS (
    MIGRATION_NAME VARCHAR NOT NULL,
    APPLIED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    APPLIED_BY VARCHAR NOT NULL DEFAULT CURRENT_USER(),
    CONSTRAINT PK_SCHEMA_MIGRATIONS PRIMARY KEY (MIGRATION_NAME)
);

MERGE INTO SCHEMA_MIGRATIONS target
USING (SELECT '001_create_app_tables.sql' AS MIGRATION_NAME) source
ON target.MIGRATION_NAME = source.MIGRATION_NAME
WHEN NOT MATCHED THEN INSERT (MIGRATION_NAME) VALUES (source.MIGRATION_NAME);
