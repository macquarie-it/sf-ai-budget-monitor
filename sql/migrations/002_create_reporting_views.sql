-- Curated reporting contract for the Streamlit application.
-- Agent TOKEN_CREDITS already include Agent-orchestrated Analyst token usage.
-- Standalone Analyst rows are sourced separately from CORTEX_ANALYST_USAGE_HISTORY.

CREATE OR REPLACE VIEW V_COST_EVENTS AS
WITH MAPPINGS AS (
    SELECT SERVICE_TYPE, WORKLOAD_NAME, TEAM, COST_CENTER, ENVIRONMENT
    FROM OWNERSHIP_MAPPINGS
    WHERE ENABLED
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SERVICE_TYPE, WORKLOAD_NAME
        ORDER BY UPDATED_AT DESC
    ) = 1
),
AGENT_EVENTS AS (
    SELECT
        A.START_TIME AS EVENT_TIME,
        'Cortex Agent' AS SERVICE_TYPE,
        COALESCE(A.AGENT_NAME, 'Unassigned') AS WORKLOAD_NAME,
        COALESCE(A.USER_NAME, 'Unassigned') AS USER_NAME,
        COALESCE(A.METADATA:role_name::VARCHAR, 'Unassigned') AS ROLE_NAME,
        COALESCE(M.TEAM, 'Unassigned') AS TEAM,
        COALESCE(M.COST_CENTER, 'Unassigned') AS COST_CENTER,
        COALESCE(M.ENVIRONMENT, 'Production') AS ENVIRONMENT,
        COALESCE(TO_VARCHAR(A.METADATA:sql_query_warehouses), '') AS WAREHOUSE_NAME,
        A.REQUEST_ID AS REQUEST_ID,
        NULL::VARCHAR AS QUERY_ID,
        COALESCE(A.TOKEN_CREDITS, 0)::NUMBER(20, 9) AS TOKEN_CREDITS,
        COALESCE(A.METADATA:ai_functions_credits::NUMBER, 0)::NUMBER(20, 9)
            AS AI_FUNCTION_CREDITS,
        (
            COALESCE(A.TOKEN_CREDITS, 0)
            + COALESCE(A.METADATA:ai_functions_credits::NUMBER, 0)
        )::NUMBER(20, 9) AS DIRECT_AI_CREDITS,
        COALESCE(A.METADATA:sql_query_credits::NUMBER, 0)::NUMBER(20, 9)
            AS COMPUTE_CREDITS,
        (
            COALESCE(A.TOKEN_CREDITS, 0)
            + COALESCE(A.METADATA:ai_functions_credits::NUMBER, 0)
            + COALESCE(A.METADATA:sql_query_credits::NUMBER, 0)
        )::NUMBER(20, 9) AS TOTAL_CREDITS,
        COALESCE(A.TOKENS, 0)::NUMBER AS TOKENS,
        1::NUMBER AS REQUEST_COUNT,
        'Unknown' AS OUTCOME,
        CASE
            WHEN A.AGENT_NAME IS NULL AND A.USER_NAME IS NULL THEN 'Unattributed'
            WHEN A.METADATA:sql_query_credits IS NULL THEN 'Partial'
            ELSE 'Complete'
        END AS ATTRIBUTION_STATUS
    FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY A
    LEFT JOIN MAPPINGS M
        ON M.SERVICE_TYPE = 'Cortex Agent'
       AND M.WORKLOAD_NAME = A.AGENT_NAME
),
STANDALONE_ANALYST_EVENTS AS (
    SELECT
        A.START_TIME AS EVENT_TIME,
        'Cortex Analyst' AS SERVICE_TYPE,
        'Standalone Cortex Analyst' AS WORKLOAD_NAME,
        COALESCE(A.USERNAME, 'Unassigned') AS USER_NAME,
        'Unassigned' AS ROLE_NAME,
        COALESCE(M.TEAM, 'Unassigned') AS TEAM,
        COALESCE(M.COST_CENTER, 'Unassigned') AS COST_CENTER,
        COALESCE(M.ENVIRONMENT, 'Production') AS ENVIRONMENT,
        '' AS WAREHOUSE_NAME,
        'analyst-hour:' || TO_VARCHAR(A.START_TIME) || ':' || COALESCE(A.USERNAME, 'unknown')
            AS REQUEST_ID,
        NULL::VARCHAR AS QUERY_ID,
        COALESCE(A.CREDITS, 0)::NUMBER(20, 9) AS TOKEN_CREDITS,
        0::NUMBER(20, 9) AS AI_FUNCTION_CREDITS,
        COALESCE(A.CREDITS, 0)::NUMBER(20, 9) AS DIRECT_AI_CREDITS,
        0::NUMBER(20, 9) AS COMPUTE_CREDITS,
        COALESCE(A.CREDITS, 0)::NUMBER(20, 9) AS TOTAL_CREDITS,
        0::NUMBER AS TOKENS,
        COALESCE(A.REQUEST_COUNT, 0)::NUMBER AS REQUEST_COUNT,
        'Succeeded' AS OUTCOME,
        'Partial' AS ATTRIBUTION_STATUS
    FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_ANALYST_USAGE_HISTORY A
    LEFT JOIN MAPPINGS M
        ON M.SERVICE_TYPE = 'Cortex Analyst'
       AND M.WORKLOAD_NAME = 'Standalone Cortex Analyst'
)
SELECT * FROM AGENT_EVENTS
UNION ALL
SELECT * FROM STANDALONE_ANALYST_EVENTS;

CREATE OR REPLACE VIEW V_DAILY_COST AS
SELECT
    DATE_TRUNC('DAY', EVENT_TIME) AS USAGE_DATE,
    SERVICE_TYPE,
    WORKLOAD_NAME,
    TEAM,
    ENVIRONMENT,
    SUM(DIRECT_AI_CREDITS) AS DIRECT_AI_CREDITS,
    SUM(COMPUTE_CREDITS) AS COMPUTE_CREDITS,
    SUM(TOTAL_CREDITS) AS TOTAL_CREDITS,
    SUM(REQUEST_COUNT) AS REQUEST_COUNT,
    SUM(IFF(ATTRIBUTION_STATUS = 'Complete', TOTAL_CREDITS, 0)) AS ATTRIBUTED_CREDITS
FROM V_COST_EVENTS
GROUP BY ALL;

MERGE INTO SCHEMA_MIGRATIONS target
USING (SELECT '002_create_reporting_views.sql' AS MIGRATION_NAME) source
ON target.MIGRATION_NAME = source.MIGRATION_NAME
WHEN NOT MATCHED THEN INSERT (MIGRATION_NAME) VALUES (source.MIGRATION_NAME);
