-- Safe defaults. Existing business-owned values are never overwritten.

MERGE INTO BUDGETS target
USING (
    SELECT
        'All Cortex Monthly' AS BUDGET_NAME,
        'Account' AS SCOPE_TYPE,
        'ALL' AS SCOPE_VALUE,
        1000::NUMBER(20, 6) AS MONTHLY_LIMIT_CREDITS,
        0.70::NUMBER(5, 4) AS WARNING_THRESHOLD,
        0.90::NUMBER(5, 4) AS CRITICAL_THRESHOLD
) source
ON target.BUDGET_NAME = source.BUDGET_NAME
WHEN NOT MATCHED THEN INSERT (
    BUDGET_NAME, SCOPE_TYPE, SCOPE_VALUE, MONTHLY_LIMIT_CREDITS,
    WARNING_THRESHOLD, CRITICAL_THRESHOLD
) VALUES (
    source.BUDGET_NAME, source.SCOPE_TYPE, source.SCOPE_VALUE,
    source.MONTHLY_LIMIT_CREDITS, source.WARNING_THRESHOLD, source.CRITICAL_THRESHOLD
);

MERGE INTO OWNERSHIP_MAPPINGS target
USING (
    SELECT
        'Cortex Analyst' AS SERVICE_TYPE,
        'Standalone Cortex Analyst' AS WORKLOAD_NAME,
        'Unassigned' AS TEAM,
        'Unassigned' AS COST_CENTER,
        'Production' AS ENVIRONMENT
) source
ON target.SERVICE_TYPE = source.SERVICE_TYPE
AND target.WORKLOAD_NAME = source.WORKLOAD_NAME
WHEN NOT MATCHED THEN INSERT (
    SERVICE_TYPE, WORKLOAD_NAME, TEAM, COST_CENTER, ENVIRONMENT
) VALUES (
    source.SERVICE_TYPE, source.WORKLOAD_NAME, source.TEAM,
    source.COST_CENTER, source.ENVIRONMENT
);

MERGE INTO SCHEMA_MIGRATIONS target
USING (SELECT '003_seed_configuration.sql' AS MIGRATION_NAME) source
ON target.MIGRATION_NAME = source.MIGRATION_NAME
WHEN NOT MATCHED THEN INSERT (MIGRATION_NAME) VALUES (source.MIGRATION_NAME);
